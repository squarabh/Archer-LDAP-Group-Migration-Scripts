DECLARE @src_count INT = (SELECT COUNT(*) FROM #Src);
IF @src_count = 0
BEGIN
    PRINT 'NOTICE: #Src table is empty. Paste rows generated by Export-ArcherLdapGroups.sql above.';
    SET NOEXEC ON;
    RETURN;
END
PRINT 'Payload loaded: ' + CAST(@src_count AS VARCHAR(10)) + ' group(s) staged.';
PRINT '';

-- 4. Staging Table: Paste Exported Hierarchy Edges Here (optional)
IF OBJECT_ID('tempdb..#SrcHier') IS NOT NULL DROP TABLE #SrcHier;
CREATE TABLE #SrcHier (
    parent_guid UNIQUEIDENTIFIER NOT NULL,
    child_guid UNIQUEIDENTIFIER NOT NULL
);

/* ----------------------------------------------------------------------------
   >>> PASTE HIERARCHY ROWS FROM Export-ArcherLdapGroups.sql BELOW THIS LINE <<<
   (leave empty if the source has no hierarchy — edges are optional)
   ---------------------------------------------------------------------------- */

-- EXAMPLE PLACEHOLDERS (fictional GUIDs — parent first, then child):
-- INSERT INTO #SrcHier VALUES ('AAAAAAAA-AAAA-4AAA-8AAA-AAAAAAAAAAAA', 'BBBBBBBB-BBBB-4BBB-8BBB-BBBBBBBBBBBB');
-- INSERT INTO #SrcHier VALUES ('AAAAAAAA-AAAA-4AAA-8AAA-AAAAAAAAAAAA', 'CCCCCCCC-CCCC-4CCC-8CCC-CCCCCCCCCCCC');

/* ----------------------------------------------------------------------------
   >>> END OF PASTED HIERARCHY ROWS <<<
   ---------------------------------------------------------------------------- */

DECLARE @hier_count INT = (SELECT COUNT(*) FROM #SrcHier);
PRINT 'Hierarchy payload: ' + CAST(@hier_count AS VARCHAR(10)) + ' edge(s) staged.';
PRINT '';

-- 5. Pre-Import Analysis: Matched vs Missing
PRINT '----------------------------------------------------------------------------';
PRINT '--- PRE-IMPORT ANALYSIS: MATCHED VS MISSING                              ---';
PRINT '----------------------------------------------------------------------------';

SELECT 
    s.group_name AS [Source_GroupName],
    s.guid AS [Source_GUID],
    g.group_id AS [Target_GroupId],
    g.group_name AS [Target_GroupName],
    CASE 
        WHEN g.group_id IS NULL THEN 'MISSING (Will be inserted)'
        WHEN g.group_name <> s.group_name THEN 'MATCHED BY GUID (Name differs in target)'
        ELSE 'MATCHED (Already exists)'
    END AS [Status]
FROM #Src s
LEFT JOIN dbo.tblGroup g ON g.guid = s.guid;

-- Check for Name Collisions (Same Name, Different GUID)
DECLARE @conflict_count INT;
SELECT @conflict_count = COUNT(*)
FROM #Src s
JOIN dbo.tblGroup g ON g.group_name = s.group_name
WHERE g.guid <> s.guid;

IF @conflict_count > 0
BEGIN
    PRINT '';
    PRINT 'WARNING: ' + CAST(@conflict_count AS VARCHAR(10)) + ' name collision(s) detected:';
    SELECT 
        s.group_name AS [ConflictingName],
        s.guid AS [Source_GUID_Expected],
        g.guid AS [Target_GUID_Existing],
        g.group_id AS [Target_GroupId]
    FROM #Src s
    JOIN dbo.tblGroup g ON g.group_name = s.group_name
    WHERE g.guid <> s.guid;
    PRINT 'NOTE: These groups will be skipped to protect existing target groups.';
END
PRINT '';

-- 6. Dynamic Audit Login Resolution
DECLARE @admin_login INT = 2;
IF NOT EXISTS (SELECT 1 FROM dbo.tblUser WHERE user_id = @admin_login)
BEGIN
    -- NOTE: zero-row SELECT leaves @admin_login unchanged, so NULL it first;
    -- otherwise the IS NULL fallback below can never fire.
    SET @admin_login = NULL;
    SELECT TOP 1 @admin_login = user_id FROM dbo.tblUser WHERE user_username = 'sysadmin';
    IF @admin_login IS NULL
        SELECT TOP 1 @admin_login = user_id FROM dbo.tblUser ORDER BY user_id ASC;
END
PRINT 'Audit Login ID to use: ' + CAST(@admin_login AS VARCHAR(10));

-- 7. Insert Missing Groups
PRINT '----------------------------------------------------------------------------';
PRINT '--- INSERTING MISSING PLACEHOLDER GROUPS                                        ---';
PRINT '----------------------------------------------------------------------------';

INSERT INTO dbo.tblGroup
    (group_name, group_desc, create_date, create_login, update_date, update_login,
     everyone, guid, [system], distinguished_name, ldap_config_id)
SELECT 
    s.group_name, 
    N'Migrated LDAP placeholder group for offline packaging', 
    GETDATE(), 
    @admin_login, 
    GETDATE(), 
    @admin_login, 
    0, 
    s.guid, 
    0, 
    NULL, 
    NULL
FROM #Src s
WHERE NOT EXISTS (SELECT 1 FROM dbo.tblGroup g WHERE g.guid = s.guid)
  AND NOT EXISTS (SELECT 1 FROM dbo.tblGroup g2 WHERE g2.group_name = s.group_name AND g2.guid <> s.guid);

DECLARE @inserted_count INT = @@ROWCOUNT;
PRINT 'Newly Inserted Groups: ' + CAST(@inserted_count AS VARCHAR(10));
PRINT '';

-- 8. Insert Hierarchy Edges (resolved by GUID, mirroring the Python importer)
PRINT '----------------------------------------------------------------------------';
PRINT '--- INSERTING HIERARCHY EDGES                                          ---';
PRINT '----------------------------------------------------------------------------';

INSERT INTO dbo.tblGroupRelationships (parent_group_id, child_group_id, create_date, create_login)
SELECT pg.group_id, cg.group_id, GETDATE(), @admin_login
FROM #SrcHier h
JOIN dbo.tblGroup pg ON pg.guid = h.parent_guid
JOIN dbo.tblGroup cg ON cg.guid = h.child_guid
WHERE NOT EXISTS (SELECT 1 FROM dbo.tblGroupRelationships r
                  WHERE r.parent_group_id = pg.group_id AND r.child_group_id = cg.group_id);

DECLARE @edges_added INT = @@ROWCOUNT;
PRINT 'Hierarchy edges added: ' + CAST(@edges_added AS VARCHAR(10));
IF EXISTS (SELECT 1 FROM #SrcHier h
           LEFT JOIN dbo.tblGroup pg ON pg.guid = h.parent_guid
           LEFT JOIN dbo.tblGroup cg ON cg.guid = h.child_guid
           WHERE pg.group_id IS NULL OR cg.group_id IS NULL)
BEGIN
    PRINT 'NOTE: some staged edges reference GUIDs missing from dbo.tblGroup and were skipped.';
    SELECT h.parent_guid AS [Unresolved_Parent_GUID], h.child_guid AS [Unresolved_Child_GUID]
    FROM #SrcHier h
    LEFT JOIN dbo.tblGroup pg ON pg.guid = h.parent_guid
    LEFT JOIN dbo.tblGroup cg ON cg.guid = h.child_guid
    WHERE pg.group_id IS NULL OR cg.group_id IS NULL;
END
PRINT '';

-- 9. Verification Check (confirms every source GUID now exists in dbo.tblGroup,
--    which is what the package installer matches on)
PRINT '----------------------------------------------------------------------------';
PRINT '--- VERIFICATION (package installer GUID match check)                  ---';
PRINT '----------------------------------------------------------------------------';

DECLARE @matched_total INT;
SELECT @matched_total = COUNT(*)
FROM dbo.tblGroup g
JOIN #Src s ON s.guid = g.guid;

PRINT 'Total Required Groups: ' + CAST(@src_count AS VARCHAR(10));
PRINT 'Total Matched in DB  : ' + CAST(@matched_total AS VARCHAR(10));

IF @matched_total = @src_count
BEGIN
    PRINT '';
    PRINT 'SUCCESS: All groups are present in the target database.';
    PRINT 'You may now proceed with the Archer Application Package installation.';
END
ELSE
BEGIN
    PRINT '';
    PRINT 'WARNING: ' + CAST((@src_count - @matched_total) AS VARCHAR(10)) + ' group(s) could not be matched.';
    PRINT 'Review the name collisions above before package install.';
END
GO

SET NOEXEC OFF;
GO
