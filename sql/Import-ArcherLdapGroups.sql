/* ============================================================================
   Import-ArcherLdapGroups.sql
   Archer LDAP Group Migration (SQL-Only Sub-Project)

   PURPOSE:
     Imports LDAP group placeholders into the TARGET Archer instance database as
     local groups with the EXACT source GUIDs (ldap_config_id = NULL,
     distinguished_name = NULL).

     This enables Archer packages containing LDAP group authorizations to
     auto-map and install successfully without requiring active LDAP sync.

   REQUIREMENTS:
     - Run against the TARGET Archer instance database in SSMS or sqlcmd.
     - Permissions: db_datawriter, db_owner, or sysadmin (preflight-guarded).

   SAFETY:
     - Idempotent: safe to run multiple times without duplicating groups.
     - Auth & Wrong-Database guards abort BEFORE any write.
     - Does not overwrite or delete existing groups.
     - Bypasses LDAP sync requirement by creating offline local placeholders.
   ============================================================================ */

SET NOCOUNT ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

-- 1. Preflight Auth & Permissions
DECLARE @login SYSNAME = SUSER_SNAME();
DECLARE @db SYSNAME = DB_NAME();
DECLARE @is_owner INT = ISNULL(IS_MEMBER('db_owner'), 0);
DECLARE @can_write INT = ISNULL(IS_MEMBER('db_datawriter'), 0);
DECLARE @is_sysadmin INT = ISNULL(IS_SRVROLEMEMBER('sysadmin'), 0);

PRINT '============================================================================';
PRINT ' ARCHER LDAP GROUP IMPORT (TARGET DATABASE: ' + DB_NAME() + ')';
PRINT ' Current Login: ' + @login;
PRINT '============================================================================';

IF (@is_owner <> 1 AND @can_write <> 1 AND @is_sysadmin <> 1)
BEGIN
    RAISERROR('AUTH FAILED: Login [%s] requires db_datawriter, db_owner, or sysadmin on [%s]. No changes made.', 16, 1, @login, @db);
    SET NOEXEC ON;
    RETURN;
END

-- 2. Preflight Target Database Name (uses @db declared above)
IF @db IN ('master', 'model', 'msdb', 'tempdb')
BEGIN
    RAISERROR('DATABASE CHECK FAILED: Connected to system database [%s]. Point SSMS at the TARGET Archer instance database.', 16, 1, @db);
    SET NOEXEC ON;
    RETURN;
END

IF OBJECT_ID('dbo.tblGroup', 'U') IS NULL
BEGIN
    RAISERROR('SCHEMA CHECK FAILED: dbo.tblGroup not found in [%s]. Is this a valid Archer instance database?', 16, 1, @db);
    SET NOEXEC ON;
    RETURN;
END
GO

-- 3. Staging Table: Paste Exported Groups Here
IF OBJECT_ID('tempdb..#Src') IS NOT NULL DROP TABLE #Src;
CREATE TABLE #Src (
    group_name NVARCHAR(500) NOT NULL, 
    guid UNIQUEIDENTIFIER NOT NULL
);

